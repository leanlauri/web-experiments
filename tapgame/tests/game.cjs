const vm=require('node:vm');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const context=new Proxy({}, {get:()=>()=>{}});
const elements=new Map();
const element=id=>{if(!elements.has(id))elements.set(id,{textContent:'',style:{},innerHTML:'',hidden:false,classList:{add(){},remove(){}},setAttribute(){},addEventListener(){},focus(){},getContext(){return context}});return elements.get(id)};
const sandbox={document:{getElementById:element,querySelectorAll:()=>[],addEventListener(){}},window:{addEventListener(){}},performance:{now:()=>0},requestAnimationFrame(){},console};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('public/game.js','utf8'),sandbox);
const run=code=>vm.runInContext(code,sandbox);
run('begin()');
assert.equal(run('state'),'playing');
assert.equal(run('items.length'),8);
assert.equal(run('blocked(250,250)'),true);
assert.equal(run('blocked(375,250)'),false);
run("keys.add('ArrowRight');update(.1);keys.clear()");
assert.ok(run('player.x')>95);
run('player.x=120;player.y=200;update(.01)');
assert.equal(run('items[0].collected'),true);
run('player.x=carts[0].x;player.y=carts[0].y;splash()');
assert.equal(run('carts[0].stun'),3);
assert.equal(run('cooldown'),2);
run('pause()');assert.equal(run('state'),'paused');
run('pause()');assert.equal(run('state'),'playing');
assert.equal(run('items[0].collected'),true);
run('cooldown=0;carts[0].stun=0;player.x=carts[0].x;player.y=carts[0].y;update(.01)');
assert.equal(run('player.hearts'),2);
run('update(.01)');assert.equal(run('player.hearts'),2);
run('items.forEach(i=>i.collected=true);player.x=790;player.y=550;update(.01)');
assert.equal(run('state'),'won');
run('begin()');assert.equal(run('player.hearts'),3);
assert.equal(run('items.some(i=>i.collected)'),false);
run('player.hearts=1;player.x=carts[0].x;player.y=carts[0].y;update(.01)');
assert.equal(run('state'),'lost');
run('draw()');
console.log('PASS movement, shelf collisions, collection, splash, pause/resume, damage immunity, checkout, restart, loss, and rendering');

run('begin();player.x=keeper.x;player.y=keeper.y;splash()');
assert.ok(run('suspicion')>=26,'Visible splash raises suspicion');
run('elapsed=lastMischief+5;player.x=375;player.y=300;updateKeeper(1)');
assert.ok(run('suspicion')<26,'Suspicion cools down');
run('suspicion=75;player.x=keeper.x;player.y=keeper.y;updateKeeper(.01)');
assert.equal(run('state'),'lost','Shopkeeper catches suspicious player');
run('begin()');assert.equal(run('suspicion'),0,'Restart clears suspicion');
run('keeper.x=120;keeper.y=300;player.x=375;player.y=300');
assert.equal(run('canSeeKeeper()'),false,'Shelves block shopkeeper sight');
run('draw()');console.log('PASS customers, witnessed splashes, suspicion cooling, shopkeeper catch, reset and blocked sight');
// A 116px stick centred on (58,58), matching the visible control.
element('thumbstick').getBoundingClientRect=()=>({left:0,top:0,width:116,height:116});
run('begin();stick.pointer=7;moveStick(58,58)');
assert.equal(run('stick.x'),0,'Stick centre is neutral');
run('moveStick(59,59)');assert.equal(run('stick.x'),0,'Small thumb movement stays in dead zone');
run('moveStick(1000,58)');assert.equal(run('stick.x'),1,'Long drags clamp to full speed');
run('moveStick(1000,1000)');assert.ok(Math.abs(run('Math.hypot(stick.x,stick.y)')-1)<.0001,'Diagonal speed is capped');
run('moveStick(76,58);const beforeStickX=player.x;update(.1)');
assert.ok(run('player.x-beforeStickX')>0&&run('player.x-beforeStickX')<18.5,'Partial drag gives slower movement');
run('releaseStick()');assert.equal(run('stick.pointer'),null);assert.equal(run('stick.x'),0);
run('stick.pointer=8;moveStick(90,58);pause()');assert.equal(run('stick.x'),0,'Pausing clears held input');
console.log('PASS thumbstick centre, dead zone, clamping, diagonal speed, analog walking, release and pause');
